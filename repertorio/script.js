function matchesSearch(song, query) {
  if (!query) return true;
  return [song.id, song.artist, song.title, getSongGenre(song), song.styles, song.key, song.difficulty, getStatusLabel(song.status)]
    .map(normalize)
    .some((field) => field.includes(query));
}

function getSortValue(song, key) {
  if (key === "genre") return getSongGenre(song);
  if (key === "difficulty") return Number(song.difficulty) || 0;
  return song[key] || "";
}

function sortSongs(songs) {
  if (!activeSort.key) return songs;

  return [...songs].sort((firstSong, secondSong) => {
    const firstRawValue = getSortValue(firstSong, activeSort.key);
    const secondRawValue = getSortValue(secondSong, activeSort.key);
    const comparison = typeof firstRawValue === "number" && typeof secondRawValue === "number"
      ? firstRawValue - secondRawValue
      : normalize(firstRawValue).localeCompare(normalize(secondRawValue), currentLang, { sensitivity: "base" });
    return activeSort.direction === "asc" ? comparison : comparison * -1;
  });
}

function renderSortButtons() {
  sortButtons.forEach((button) => {
    const isActive = button.dataset.sortKey === activeSort.key;
    const direction = isActive ? activeSort.direction : "";
    button.dataset.sortDirection = direction;
    button.closest("th").setAttribute(
      "aria-sort",
      isActive ? (direction === "asc" ? "ascending" : "descending") : "none"
    );
  });
}

function renderRows() {
  const query = normalize(searchInput.value.trim());
  const genre = genreFilter.value;
  const status = statusFilter.value;

  const visibleSongs = sortSongs(repertoire.filter((song) => {
    const genreMatch = genre === "all" || song.codes.includes(genre);
    const statusMatch = status === "all" || song.status === status;
    return genreMatch && statusMatch && matchesSearch(song, query);
  }));

  tableBody.innerHTML = visibleSongs
    .map((song) => {
      const statusClass = `song__status${song.status === "To learn" ? " song__status--learn" : ""}${song.status === "Partitura" ? " song__status--sheet" : ""}`;
      return `
        <tr>
          <td class="${song.artist === "Por confirmar" ? "muted" : ""}">${song.artist}</td>
          <td>
            <div class="song">
              <span class="song__title">${song.title}</span>
              <span class="${statusClass}">${getStatusLabel(song.status)}</span>
            </div>
          </td>
          <td>${getSongGenre(song)}</td>
          <td><span class="key">${song.key}</span></td>
          <td><span class="group">${song.difficulty}</span></td>
        </tr>
      `;
    })
    .join("");

  resultCount.textContent = `${visibleSongs.length} ${visibleSongs.length === 1 ? t("result") : t("results")}`;
  emptyState.hidden = visibleSongs.length > 0;
  renderSortButtons();
}

