const normalize = (value) =>
  value
    .toString()
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "");

function getStatusLabel(status) {
  if (status === "To learn") return t("statusLearn");
  if (status === "Partitura") return t("statusSheet");
  return t("statusReady");
}

function getSetLabel(set) {
  return set.labelKey ? t(set.labelKey) : set.name;
}

